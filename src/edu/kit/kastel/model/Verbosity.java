package edu.kit.kastel.model;

/**
 * The Enum Verbosity represents the way the board is shown in the output.
 * @author uqibg
 */
public enum Verbosity {
    /**
     * The all verbosity level shows the board with the row an edge lines and the field coordinates.
     */
    ALL,
    /**
     * The compact verbosity level shows the board limited to the fields and the vertical line separating them.
     */
    COMPACT
}
